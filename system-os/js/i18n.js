function currentLang() {
  return (window.Core && Core.state && Core.state.lang) ? Core.state.lang : 'ar';
}

function t(key, params) {
  var entry = I18N[key];
  var lang = currentLang();
  var str = entry ? (entry[lang] || entry.en || key) : key;
  if (params) {
    Object.keys(params).forEach(function (k) {
      var v = params[k];
      if (v && typeof v === 'object' && v.i18n) v = t(v.i18n);
      if (v === null || v === undefined) v = '';
      str = str.split('{' + k + '}').join(String(v));
    });
  }
  return str;
}
